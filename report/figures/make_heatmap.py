"""Figure 2 of the report: resolved runs (of 3) per task and configuration.

Reads the official verdicts of the final runs (final_results/runs/final-t4{,-r2,-r3}-<config>)
and writes the matrix as CSV and as a LaTeX table with shaded cells. Tasks are sorted by their
total over all configurations (most often resolved first).

    python report/figures/make_heatmap.py [--runs final_results/runs] [--out report/figures/heatmap]
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

TAGS = ("final-t4", "final-t4-r2", "final-t4-r3")
CONFIGS = (("pcr", "P-C-R"), ("single", "Single"), ("pcr-low", "P-C-R, low"),
           ("pcr-high", "P-C-R, high"), ("pcr-max", "P-C-R, max"),
           ("pcr-exec", "P-C-R + exec"), ("single-exec", "Single + exec"))


def resolved(batch: Path) -> dict[str, bool]:
    tasks = json.loads((batch / "official_eval.json").read_text(encoding="utf-8"))["tasks"]
    return {iid: verdict == "resolved" for iid, verdict in tasks.items()}


def matrix(runs: Path) -> tuple[list[str], dict[str, dict[str, int]]]:
    counts: dict[str, dict[str, int]] = {}
    for config, _ in CONFIGS:
        per_task: dict[str, int] = {}
        for tag in TAGS:
            for iid, ok in resolved(runs / f"{tag}-{config}").items():
                per_task[iid] = per_task.get(iid, 0) + int(ok)
        counts[config] = per_task
    tasks = sorted(counts["pcr"], key=lambda t: (-sum(c[t] for c in counts.values()), t))
    return tasks, counts


def short(iid: str) -> str:
    repo, number = iid.split("__", 1)[1].rsplit("-", 1)
    return f"{repo.replace('-python', '')}-{number}"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--runs", type=Path, default=Path("final_results/runs"))
    parser.add_argument("--out", type=Path, default=Path("report/figures/heatmap"))
    args = parser.parse_args()
    tasks, counts = matrix(args.runs)
    totals = [sum(c[t] for c in counts.values()) for t in tasks]
    args.out.parent.mkdir(parents=True, exist_ok=True)

    with open(f"{args.out}.csv", "w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(["configuration", *(short(t) for t in tasks)])
        for config, label in CONFIGS:
            writer.writerow([label, *(counts[config][t] for t in tasks)])
        writer.writerow([f"Total (of {3 * len(CONFIGS)})", *totals])

    shade = {0: "", 1: "\\cellcolor{blue!20}", 2: "\\cellcolor{blue!45}", 3: "\\cellcolor{blue!75}"}
    lines = ["% generated by report/figures/make_heatmap.py; needs \\usepackage[table]{xcolor}",
             "\\begin{tabular}{l" + "c" * len(tasks) + "}",
             " & " + " & ".join(f"\\rotatebox{{90}}{{\\texttt{{{short(t)}}}}}" for t in tasks) + " \\\\"]
    for config, label in CONFIGS:
        lines.append(label + " & " + " & ".join(f"{shade[counts[config][t]]}{counts[config][t]}"
                                               for t in tasks) + " \\\\")
    lines += ["\\hline", f"Total (of {3 * len(CONFIGS)}) & " + " & ".join(map(str, totals)) + " \\\\",
              "\\end{tabular}"]
    Path(f"{args.out}.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out}.csv and {args.out}.tex ({len(tasks)} tasks)")
    print("totals:", " ".join(map(str, totals)))


if __name__ == "__main__":
    main()
