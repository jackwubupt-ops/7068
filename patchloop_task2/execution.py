"""Docker-only, bounded execution of repository-specific tests.

Test commands and images are operator-provided, never generated by the LLM.
Docker must already be installed and its image pre-pulled by the operator.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import time
import uuid


@dataclass(frozen=True)
class DockerTestSpec:
    image: str
    command: tuple[str, ...] = ("python", "-m", "unittest", "discover", "-s", "tests", "-v")
    timeout_seconds: int = 90
    memory_mb: int = 1024
    cpus: float = 1.0
    pids_limit: int = 128

    def __post_init__(self):
        # This configuration must originate from the trusted operator, not Issue text.
        if not isinstance(self.image, str) or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._:/@-]{0,199}", self.image):
            raise ValueError("Provide a trusted Docker image name/digest")
        if not isinstance(self.command, tuple) or not 1 <= len(self.command) <= 20 or any(
            not isinstance(c, str) or not c or len(c) > 300 or "\x00" in c or "\n" in c
            for c in self.command
        ):
            raise ValueError("Test command must be a bounded tuple of argv elements")
        if not isinstance(self.timeout_seconds, int) or not 5 <= self.timeout_seconds <= 600:
            raise ValueError("timeout_seconds must be 5..600")
        if not isinstance(self.memory_mb, int) or not 128 <= self.memory_mb <= 8192:
            raise ValueError("memory_mb must be 128..8192")
        if not isinstance(self.cpus, (float, int)) or not 0.1 <= self.cpus <= 4:
            raise ValueError("cpus must be 0.1..4")
        if not isinstance(self.pids_limit, int) or not 32 <= self.pids_limit <= 512:
            raise ValueError("pids_limit must be 32..512")


@dataclass(frozen=True)
class TestOutcome:
    status: str
    exit_code: int | None
    output_tail: str
    duration_seconds: float

    def to_dict(self) -> dict:
        return asdict(self)


class DockerTestRunner:
    def run(self, workspace: Path, spec: DockerTestSpec) -> TestOutcome:
        start = time.monotonic()
        if not shutil.which("docker"):
            return TestOutcome("docker_error", None, "Docker CLI unavailable", 0.0)
        if not workspace.is_dir():
            return TestOutcome("docker_error", None, "Workspace missing", 0.0)
        name = "patchloop-" + uuid.uuid4().hex[:16]
        command = [
            "docker", "run", "--rm", "--name", name, "--pull", "never",
            "--network", "none", "--read-only",
            "--cap-drop", "ALL", "--security-opt", "no-new-privileges",
            "--user", "65534:65534", "--pids-limit", str(spec.pids_limit),
            "--memory", f"{spec.memory_mb}m", "--cpus", str(spec.cpus),
            "--tmpfs", "/tmp:rw,nosuid,nodev,size=64m",
            "--workdir", "/workspace",
            "--mount", f"type=bind,src={workspace.resolve()},dst=/workspace,readonly",
            "-e", "PYTHONDONTWRITEBYTECODE=1", "-e", "PYTHONNOUSERSITE=1",
            "-e", "HOME=/tmp", "-e", "PYTHONPATH=/workspace",
            spec.image, *spec.command,
        ]
        try:
            with tempfile.TemporaryFile() as output:
                process = subprocess.Popen(command, stdout=output, stderr=subprocess.STDOUT)
                try:
                    exit_code = process.wait(timeout=spec.timeout_seconds)
                except subprocess.TimeoutExpired:
                    process.kill()
                    process.wait(timeout=10)
                    # Killing the Docker CLI alone is not enough; stop the actual container.
                    subprocess.run(["docker", "rm", "-f", name],
                                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                                   timeout=15, check=False)
                    output.seek(0, 2)
                    size = output.tell()
                    output.seek(max(0, size - 8000))
                    tail = output.read().decode("utf-8", "replace")
                    return TestOutcome("timeout", None, tail, round(time.monotonic() - start, 3))
                output.seek(0, 2)
                size = output.tell()
                output.seek(max(0, size - 8000))
                tail = output.read().decode("utf-8", "replace")
                if exit_code == 0:
                    status = "passed"
                elif any(x in tail.lower() for x in (
                    "cannot connect to the docker daemon",
                    "unable to find image",
                    "docker: error response from daemon",
                    "docker: 'run' requires",
                    "permission denied while trying to connect to the docker daemon",
                )):
                    status = "docker_error"
                else:
                    status = "failed"
                return TestOutcome(status, exit_code, tail, round(time.monotonic() - start, 3))
        except (OSError, subprocess.TimeoutExpired) as exc:
            return TestOutcome("docker_error", None, str(exc)[:1200],
                               round(time.monotonic() - start, 3))
